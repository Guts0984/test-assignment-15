#!/usr/bin/env bash
# Runs every acceptance script that does not need the full seed and writes docs/ACCEPTANCE.md.
# The full-seed performance check (acc16-perf.sh) needs the default profile and is run separately.
set -uo pipefail
cd "$(dirname "$0")/../.."
OUT=docs/ACCEPTANCE.md
{
  echo "# Acceptance run"
  echo
  echo "Generated by scripts/acceptance/run-all.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo
} > "$OUT"
status=0
for s in acc03-05-sla acc06-15-stack acc16-e2e; do
  echo "== $s"
  if out=$(bash "scripts/acceptance/$s.sh" 2>&1); then r=PASS; else r=FAIL; status=1; fi
  { echo "## $s: $r"; echo; echo '```'; echo "$out" | tail -40; echo '```'; echo; } >> "$OUT"
  echo "$r $s"
done
exit $status

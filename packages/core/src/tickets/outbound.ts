import { randomUUID } from 'node:crypto';
import { createHash, randomBytes } from 'node:crypto';
import { outboundSubject } from '@helpdesk/shared';
import type { Tx } from '../db/client';
import { upsertJob } from '../jobs/jobs';
import type { Ctx } from './types';

const DAY_MS = 86_400_000;

/** Same shape as the api's token helpers: 32 random bytes as base64url, only the SHA-256 is stored. */
export const newLinkToken = (): { token: string; hash: string } => {
  const token = randomBytes(32).toString('base64url');
  return { token, hash: createHash('sha256').update(token).digest('hex') };
};

export const createTicketLinkTx = async (
  tx: Tx,
  ticketId: string,
  now: Date,
  ttlDays: number,
): Promise<string> => {
  const { token, hash } = newLinkToken();
  await tx.$executeRaw`
    INSERT INTO ticket_access_tokens (ticket_id, token_hash, expires_at, created_at)
    VALUES (${ticketId}::uuid, ${hash}, ${new Date(now.getTime() + ttlDays * DAY_MS)}, ${now})`;
  return token;
};

export type QueueOutbound = {
  readonly ticketId: string;
  readonly messageId?: string | null;
  readonly purpose: 'reply' | 'acknowledgement' | 'survey';
  readonly toEmail: string;
  readonly subject: string;
  readonly ticketNumber: number;
  readonly bodyText: string;
  readonly inReplyTo?: string | null;
  readonly referencesHdr?: string | null;
  readonly autoGenerated: boolean;
  readonly sendAfter: Date;
  /** Link line appended to the body; a fresh single-ticket link is created unless a survey link is passed in. */
  readonly extraLink?: { readonly label: string; readonly url: string } | null;
  readonly withTicketLink?: boolean;
};

/**
 * Creates the outbound email row and its durable send job in the caller's transaction.
 * The fixed Message-ID makes a retry send the same email; the state machine prevents sending twice.
 */
export const queueOutbound = async (
  c: Ctx,
  o: QueueOutbound,
): Promise<{ id: string; rfcMessageId: string }> => {
  const id = randomUUID();
  const rfcMessageId = `${randomUUID()}@${c.cfg.mailDomain}`;
  const lines = [o.bodyText];
  if (o.extraLink !== undefined && o.extraLink !== null)
    lines.push('', `${o.extraLink.label}: ${o.extraLink.url}`);
  if (o.withTicketLink !== false && o.purpose !== 'survey') {
    const token = await createTicketLinkTx(c.tx, o.ticketId, c.now, c.cfg.linkTtlDays);
    lines.push(
      '',
      '---',
      `View and reply online (no password needed): ${c.cfg.publicBaseUrl}/portal#token=${token}`,
    );
  }
  await c.tx.$executeRaw`
    INSERT INTO outbound_emails (id, ticket_id, message_id, purpose, to_email, subject, body_text, rfc_message_id,
                                 in_reply_to, references_hdr, auto_generated, state, send_after, created_at)
    VALUES (${id}::uuid, ${o.ticketId}::uuid, ${o.messageId ?? null}::uuid, ${o.purpose}, ${o.toEmail},
            ${outboundSubject(o.ticketNumber, o.subject)}, ${lines.join('\n')}, ${rfcMessageId}, ${o.inReplyTo ?? null},
            ${o.referencesHdr ?? null}, ${o.autoGenerated}, 'scheduled', ${o.sendAfter}, ${c.now})`;
  await upsertJob(c.tx, {
    kind: 'outbound_send',
    ref: id,
    dedupeKey: `outbound:${id}`,
    runAt: o.sendAfter,
    now: c.now,
    payload: { outboundId: id },
  });
  return { id, rfcMessageId };
};

import type { OutboundMessage, SendFn } from '@helpdesk/core';
import nodemailer from 'nodemailer';

type SmtpError = { responseCode?: number; code?: string; message?: string };

/** 4xx replies and network trouble are transient (retry); 5xx replies are permanent. */
export const classifySmtpError = (e: unknown): { transient: boolean; message: string } => {
  const err = e as SmtpError;
  const message = (err.message ?? String(e)).slice(0, 300);
  if (typeof err.responseCode === 'number') return { transient: err.responseCode < 500, message };
  return { transient: true, message };
};

export type SmtpSender = { readonly send: SendFn; readonly close: () => void };

export const createSmtpSender = (o: {
  host: string;
  port: number;
  fromName: string;
}): SmtpSender => {
  const transport = nodemailer.createTransport({
    host: o.host,
    port: o.port,
    secure: false,
    ignoreTLS: true,
    pool: true,
    maxConnections: 5,
    connectionTimeout: 10_000,
    greetingTimeout: 10_000,
    socketTimeout: 30_000,
  });
  return {
    send: async (m: OutboundMessage) => {
      try {
        await transport.sendMail({
          from: { name: o.fromName, address: m.fromAddress },
          to: m.toEmail,
          subject: m.subject,
          text: m.bodyText,
          messageId: `<${m.rfcMessageId}>`,
          ...(m.inReplyTo === null ? {} : { inReplyTo: m.inReplyTo }),
          ...(m.referencesHdr === null ? {} : { references: m.referencesHdr }),
          headers: {
            ...(m.autoGenerated ? { 'Auto-Submitted': 'auto-generated' } : {}),
            'X-Helpdesk-Ticket': String(m.ticketNumber),
          },
        });
        return { ok: true as const };
      } catch (e) {
        return { ok: false as const, ...classifySmtpError(e) };
      }
    },
    close: () => transport.close(),
  };
};

/** Reference numbers are the rare tokens: thousands of distinct values, each in a tiny share of the messages. */
const reference = (rng: Rng): number => rng.int(10_000, 99_999);

type Words = {
  readonly noun: () => string;
  readonly product: () => string;
  readonly pick: <T>(a: readonly T[]) => T;
};

const SENTENCES: readonly ((w: Words, rng: Rng) => string)[] = [
  (w) =>
    `I cannot ${w.pick(VERBS)} my ${w.noun()} for the ${w.product()} and the page shows ${w.pick(PROBLEMS)}.`,
  (w, r) => `My ${w.noun()} for order ${reference(r)} is still ${w.pick(STATES)}.`,
  (w) =>
    `Please ${w.pick(VERBS)} the ${w.noun()} on my account, it has been ${w.pick(STATES)} ${w.pick(WHENS)}.`,
  (w, r) =>
    `The ${w.noun()} is ${w.pick(STATES)} again, could you check reference ${reference(r)}?`,
  (w) =>
    `I received ${w.pick(PROBLEMS)} when I tried to ${w.pick(VERBS)} the ${w.noun()} ${w.pick(WHENS)}.`,
  (w) =>
    `Your ${w.noun()} for the ${w.product()} is ${w.pick(STATES)} and I need to ${w.pick(VERBS)} it today.`,
  (w, r) =>
    `I bought the ${w.product()} ${reference(r)} ${w.pick(WHENS)} and the ${w.noun()} is ${w.pick(STATES)}.`,
  (w, r) =>
    `I contacted you about ${w.noun()} number ${reference(r)} ${w.pick(WHENS)} and nothing changed.`,
  (w) => `Can you explain why the ${w.noun()} and the ${w.noun()} do not match?`,
];

const makeWords = (rng: Rng): Words => ({
  noun: () => NOUNS[rng.skewed(NOUNS.length, 2.2)] ?? 'account',
  product: () => PRODUCTS[rng.skewed(PRODUCTS.length, 2)] ?? 'Aurora',
  pick: <T>(a: readonly T[]): T => a[rng.skewed(a.length, 1.4)] as T,
});

export const buildVocabulary = (): readonly string[] => NOUNS;

const sentence = (rng: Rng, w: Words): string => {
  const make = SENTENCES[rng.int(0, SENTENCES.length - 1)] ?? SENTENCES[0];
  return (make as (w: Words, rng: Rng) => string)(w, rng);
};

/** Pool of distinct message bodies; messages pick from it by index to keep bulk generation in SQL fast. */
export const buildBodyPool = (rng: Rng, size: number): readonly string[] => {
  const w = makeWords(rng);
  return Array.from({ length: size }, () => {
    const parts = Array.from({ length: rng.int(2, 4) }, () => sentence(rng, w));
    return `${rng.pick(OPENINGS)} ${parts.join(' ')} ${rng.pick(CLOSINGS)}`;
  });
};

const SUBJECTS: readonly ((w: Words, rng: Rng) => string)[] = [
  (w) => `Cannot ${w.pick(VERBS)} my ${w.noun()}`,
  (w) => `${w.noun()} is ${w.pick(STATES)}`,
  (w, r) => `Problem with order ${reference(r)}`,
  (w) => `Question about my ${w.noun()}`,
  (w) => `${w.pick(PROBLEMS)} on the ${w.noun()}`,
  (w) => `${w.product()} ${w.noun()} is ${w.pick(STATES)}`,
  (w) => `Please ${w.pick(VERBS)} my ${w.noun()}`,
];

export const buildSubjectPool = (rng: Rng, size: number): readonly string[] => {
  const w = makeWords(rng);
  return Array.from({ length: size }, () => {
    const make = SUBJECTS[rng.int(0, SUBJECTS.length - 1)] ?? SUBJECTS[0];
    const s = (make as (w: Words, rng: Rng) => string)(w, rng);
    return s.charAt(0).toUpperCase() + s.slice(1);
  });
};

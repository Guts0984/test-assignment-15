/** A few thousand rare tokens give search realistic selectivity (document frequency well under 1%). */
const rareWords = (count: number): readonly string[] =>
  Array.from(
    { length: count },
    (_, i) => `${COMMON[i % COMMON.length]?.slice(0, 4) ?? 'item'}x${(i * 7919) % 100_000}`,
  );

export const buildVocabulary = (): readonly string[] => [...COMMON, ...rareWords(4000)];

const sentence = (rng: Rng, vocab: readonly string[], words: number): string =>
  Array.from({ length: words }, () => vocab[rng.skewed(vocab.length, 2.2)] ?? 'help').join(' ');

/** Pool of distinct message bodies; messages pick from it by index to keep bulk generation in SQL fast. */
export const buildBodyPool = (rng: Rng, size: number): readonly string[] => {
  const vocab = buildVocabulary();
  return Array.from({ length: size }, () => {
    const first = rng.pick(['Hello,', 'Hi team,', 'Good day,', 'Dear support,', 'Hi,']);
    return `${first} ${sentence(rng, vocab, rng.int(14, 40))}. ${sentence(rng, vocab, rng.int(4, 12))}.`;
  });
};

export const buildSubjectPool = (rng: Rng, size: number): readonly string[] => {
  const vocab = buildVocabulary();
  return Array.from({ length: size }, () => {
    const s = sentence(rng, vocab, rng.int(3, 7));
    return s.charAt(0).toUpperCase() + s.slice(1);
  });
};
